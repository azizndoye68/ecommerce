CREATE TABLE jetons_reinitialisation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    jeton_hash VARCHAR(64) NOT NULL UNIQUE,
    utilisateur_id BIGINT NOT NULL REFERENCES utilisateurs(id) ON DELETE CASCADE,
    expire_le TIMESTAMP NOT NULL,
    cree_le TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_jetons_reinitialisation_utilisateur ON jetons_reinitialisation (utilisateur_id);
CREATE INDEX idx_jetons_reinitialisation_expiration ON jetons_reinitialisation (expire_le);
