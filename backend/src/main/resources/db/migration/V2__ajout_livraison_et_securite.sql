-- Mise à niveau des bases qui existaient avant les commandes avec livraison et sessions persistées.
ALTER TABLE commandes ADD COLUMN IF NOT EXISTS destinataire_livraison VARCHAR(255) NOT NULL DEFAULT 'Non renseigné';
ALTER TABLE commandes ADD COLUMN IF NOT EXISTS telephone_livraison VARCHAR(255) NOT NULL DEFAULT 'Non renseigné';
ALTER TABLE commandes ADD COLUMN IF NOT EXISTS adresse_livraison VARCHAR(1000) NOT NULL DEFAULT 'Non renseignée';
ALTER TABLE commandes ADD COLUMN IF NOT EXISTS ville_livraison VARCHAR(255) NOT NULL DEFAULT 'Non renseignée';
ALTER TABLE commandes ADD COLUMN IF NOT EXISTS pays_livraison VARCHAR(255) NOT NULL DEFAULT 'Non renseigné';
ALTER TABLE commandes ADD COLUMN IF NOT EXISTS reference_paiement VARCHAR(255);
ALTER TABLE commandes ADD COLUMN IF NOT EXISTS url_paiement VARCHAR(1000);
ALTER TABLE utilisateurs ADD COLUMN IF NOT EXISTS actif BOOLEAN NOT NULL DEFAULT TRUE;
ALTER TABLE utilisateurs ADD COLUMN IF NOT EXISTS cree_le TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP;

CREATE TABLE IF NOT EXISTS refresh_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_hash VARCHAR(64) NOT NULL UNIQUE,
    utilisateur_id BIGINT NOT NULL REFERENCES utilisateurs(id),
    expire_le TIMESTAMP NOT NULL,
    revoque BOOLEAN NOT NULL DEFAULT FALSE,
    cree_le TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS tokens_revoques (
    jti VARCHAR(255) PRIMARY KEY,
    expire_le TIMESTAMP
);

CREATE TABLE IF NOT EXISTS journal_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    acteur_id BIGINT,
    action VARCHAR(255) NOT NULL,
    ressource VARCHAR(255) NOT NULL,
    cree_le TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_audit_cree_le ON journal_audit (cree_le);
