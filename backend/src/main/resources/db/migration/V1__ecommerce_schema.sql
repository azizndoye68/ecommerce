CREATE TABLE IF NOT EXISTS utilisateurs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom VARCHAR(255) NOT NULL,
    prenom VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    mot_de_passe VARCHAR(255) NOT NULL,
    telephone VARCHAR(255), adresse VARCHAR(255), role VARCHAR(30) NOT NULL,
    actif BOOLEAN NOT NULL DEFAULT TRUE, cree_le TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, nom VARCHAR(255) NOT NULL UNIQUE, description VARCHAR(500)
);
CREATE TABLE IF NOT EXISTS produits (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, nom VARCHAR(255) NOT NULL, description VARCHAR(1000),
    prix NUMERIC(19,2) NOT NULL, quantite_stock INTEGER NOT NULL, image_url VARCHAR(255), categorie_id BIGINT REFERENCES categories(id)
);
CREATE TABLE IF NOT EXISTS paniers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, utilisateur_id BIGINT NOT NULL UNIQUE REFERENCES utilisateurs(id),
    cree_le TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, modifie_le TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS lignes_panier (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, panier_id BIGINT NOT NULL REFERENCES paniers(id),
    produit_id BIGINT NOT NULL REFERENCES produits(id), quantite INTEGER NOT NULL, UNIQUE(panier_id, produit_id)
);
CREATE TABLE IF NOT EXISTS commandes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, utilisateur_id BIGINT NOT NULL REFERENCES utilisateurs(id),
    statut VARCHAR(40) NOT NULL, mode_paiement VARCHAR(40) NOT NULL, total NUMERIC(19,2) NOT NULL,
    reference_paiement VARCHAR(255) UNIQUE, url_paiement VARCHAR(1000),
    destinataire_livraison VARCHAR(255) NOT NULL, telephone_livraison VARCHAR(255) NOT NULL,
    adresse_livraison VARCHAR(1000) NOT NULL, ville_livraison VARCHAR(255) NOT NULL, pays_livraison VARCHAR(255) NOT NULL,
    cree_le TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS lignes_commande (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, commande_id BIGINT NOT NULL REFERENCES commandes(id),
    produit_id BIGINT NOT NULL, nom_produit VARCHAR(255) NOT NULL, prix_unitaire NUMERIC(19,2) NOT NULL, quantite INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS refresh_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, token_hash VARCHAR(64) NOT NULL UNIQUE,
    utilisateur_id BIGINT NOT NULL REFERENCES utilisateurs(id), expire_le TIMESTAMP NOT NULL, revoque BOOLEAN NOT NULL DEFAULT FALSE,
    cree_le TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS tokens_revoques (jti VARCHAR(255) PRIMARY KEY, expire_le TIMESTAMP);
CREATE TABLE IF NOT EXISTS journal_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, acteur_id BIGINT, action VARCHAR(255) NOT NULL,
    ressource VARCHAR(255) NOT NULL, cree_le TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_audit_cree_le ON journal_audit (cree_le);

